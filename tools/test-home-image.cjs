const assert = require('node:assert/strict');
require('./register-typescript.cjs');
const React = require('react');
let failed = null;
React.useState = () => [failed, value => { failed = value; }];
const { HomeImage } = require('../src/components/HomeImage.tsx');
let loaded = 0, errors = 0;
const props = { src: '/articles/example.png', alt: 'Original image', fill: true, onLoad: () => loaded++, onError: () => errors++ };
let image = HomeImage(props);
assert.equal(image.props.unoptimized, false, 'Use optimization normally');
image.props.onError({});
image = HomeImage(props);
assert.equal(image.props.unoptimized, true, 'An optimizer failure falls back to the original source');
assert.equal(image.props.src, props.src);
assert.equal(image.props.alt, props.alt);
image.props.onLoad({});
assert.equal(loaded, 1, 'Hero readiness callback survives fallback');
assert.equal(errors, 1);
assert.equal(HomeImage({ ...props, src: '/articles/another.png' }).props.unoptimized, false, 'A different source can still use optimization');
assert.equal(HomeImage({ ...props, unoptimized: true }).props.unoptimized, true);
console.log('PASS: home image optimizer fallback preserves source, alt, readiness and normal optimization');
